"""开机自启：在用户的“启动”文件夹里放一个极短的启动脚本。

Windows 登录时会执行“启动”文件夹里的脚本。这里放的是一个 4 行的 VBS，
它再转去调用仓库里的 scripts/start_wallpaper_hidden.vbs，这样：

  * 启动逻辑仍然留在仓库里（可版本管理、可修改）；
  * 路径是绝对路径，移动仓库后重新执行 install 即可；
  * 不需要管理员权限，也不写入注册表。

用法：
    python python/autostart.py install
    python python/autostart.py uninstall
    python python/autostart.py status
"""

from __future__ import annotations

import os
from pathlib import Path
import sys


ROOT = Path(__file__).resolve().parent.parent
LAUNCHER = ROOT / "scripts" / "start_wallpaper_hidden.vbs"
ENTRY_NAME = "jupiter-wallpaper.vbs"


def startup_folder() -> Path:
    appdata = os.environ.get("APPDATA")
    if not appdata:
        raise RuntimeError("找不到 APPDATA，无法定位“启动”文件夹")
    return Path(appdata) / "Microsoft" / "Windows" / "Start Menu" / "Programs" / "Startup"


def entry_path() -> Path:
    return startup_folder() / ENTRY_NAME


def entry_content() -> str:
    # 一行 VBS：隐藏运行仓库里的启动脚本。窗口样式 0 = 不显示控制台。
    # 用纯 ASCII 写出：WSH 按系统代码页读取 .vbs，中文注释在某些区域设置下会乱码。
    return (
        "' Generated by python/autostart.py - delete this file to disable autostart.\r\n"
        f'CreateObject("WScript.Shell").Run """{LAUNCHER}""", 0, False\r\n'
    )


def install() -> None:
    if not LAUNCHER.is_file():
        raise FileNotFoundError(f"缺少启动脚本：{LAUNCHER}")
    path = entry_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(entry_content(), encoding="ascii", newline="")
    print(f"已设置开机自启：{path}")
    print(f"  → 登录后等待约 20 秒，再隐藏启动 {LAUNCHER.name}")
    print("  取消：双击 scripts\\uninstall_autostart.cmd")


def uninstall() -> None:
    path = entry_path()
    if path.exists():
        path.unlink()
        print(f"已取消开机自启：{path}")
    else:
        print("本来就没有设置开机自启。")
    # 顺带清掉被复制的旧版本，避免迁移目录后残留两份。
    legacy = startup_folder() / "jupiter-wallpaper.lnk"
    if legacy.exists():
        legacy.unlink()
        print(f"已删除旧的快捷方式：{legacy}")


def status() -> None:
    path = entry_path()
    if path.exists():
        print(f"开机自启：已开启\n  {path}")
        print("  内容：")
        for line in path.read_text(encoding="utf-8").splitlines():
            print(f"    {line}")
    else:
        print("开机自启：未设置")


def main() -> None:
    action = sys.argv[1].lower() if len(sys.argv) > 1 else "status"
    if action == "install":
        install()
    elif action == "uninstall":
        uninstall()
    elif action == "status":
        status()
    else:
        raise SystemExit("用法：python autostart.py [install|uninstall|status]")


if __name__ == "__main__":
    main()
